#!/bin/sh
# creates the local secrets file for the dev stack, and adds keys that a
# newer version of this script knows about to an existing file. existing
# values are never changed, because the umami admin password and the platform
# role passwords in it must keep matching the ones already in the database.
set -eu

env_file="${1:?usage: gen-env.sh <path>}"

# hex keeps the values safe inside postgres urls without escaping
rand() { od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; }

umask 077
if [ ! -f "$env_file" ]; then
  echo "# local dev secrets, generated by deploy/compose/gen-env.sh. never commit." >"$env_file"
  echo "created $env_file"
fi

has() { grep -q "^$1=" "$env_file"; }
put() {
  if ! has "$1"; then
    printf '%s=%s\n' "$1" "$2" >>"$env_file"
    echo "added $1 to $env_file"
  fi
}
get() { sed -n "s/^$1=//p" "$env_file"; }

put POSTGRES_PASSWORD "$(rand 24)"
put UMAMI_DB_PASSWORD "$(rand 24)"
put UMAMI_APP_SECRET "$(rand 32)"
put UMAMI_URL http://localhost:3000
put UMAMI_ADMIN_PASSWORD "$(rand 24)"

# platform database. platformctl db migrate connects as the postgres
# superuser of the dev stack; db roles sets the role passwords below.
put PLATFORM_DB_HOST 127.0.0.1
put PLATFORM_DB_PORT 55432
put PLATFORM_DB_NAME platform
put PLATFORM_DB_SSLMODE disable
put PLATFORM_DB_ADMIN_USER postgres
put PLATFORM_DB_ADMIN_PASSWORD "$(get POSTGRES_PASSWORD)"
put PLATFORM_DB_CP_SYSTEM_PASSWORD "$(rand 24)"
put PLATFORM_DB_CP_TENANT_PASSWORD "$(rand 24)"
put PLATFORM_DB_CP_OPERATOR_PASSWORD "$(rand 24)"
put PLATFORM_DB_METRICS_WRITER_PASSWORD "$(rand 24)"
put PLATFORM_DB_JOBS_PASSWORD "$(rand 24)"

# nats. the dev server is a single node without auth, so the
# topology uses one replica and no NATS_USER is set.
put NATS_URL nats://127.0.0.1:4222
put NATS_REPLICAS 1
