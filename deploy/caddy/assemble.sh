#!/bin/sh
# assembles the caddyfile a deployed node runs (the design) from the
# per-host caddyfiles that the earlier phases test one by one:
#
#   assemble.sh edge   edge.Caddyfile                  > node.Caddyfile
#   assemble.sh core   app.Caddyfile web.Caddyfile     > node.Caddyfile
#
# a core node serves app. and web. from one caddy, and caddy allows one
# global options block per config, so each input's global block is dropped
# and one node-level block replaces it. its default-logger filter deletes the
# same fields as the inputs' (app and web use identical lists; edge keeps its
# own list, which is reused unchanged).
#
# the node-level parts it adds:
#   - `tls {$EDGE_TLS}` and the like become `import sa_tls_{$SA_TLS}`, where
#     SA_TLS is "bunny" (acme dns-01 through caddy-dns/bunny, reading the key
#     from BUNNY_API_KEY at runtime) or "internal" (caddy's local ca, used by
#     the local converge only). dns-01 is required because three edge nodes
#     serve the same names, so an http-01 or tls-alpn challenge can land on
#     another node.
#   - port 80 answers 503 while the drain flag /drain/draining exists
#     (deploy.yml mounts it), then
#   - port 80 answers for the node's composite health, whatever the host
#     header: it asks NODE_HEALTH_UPSTREAM at NODE_HEALTH_PATH, redirects to
#     https when that answers 200 and answers 503 otherwise. the bunny.net
#     monitor counts any non-5xx as healthy, so a redirect keeps the node in
#     dns and a 503 takes it out. automatic http->https redirects are off,
#     because they would answer 308 for in. and otlp. even on a sick node.
#
# every replaced line must be found exactly once, so a change to an input
# that this script does not understand fails the deploy instead of shipping
# a config without dns-01 or health.
set -eu

tier="${1:?usage: assemble.sh edge|core <caddyfile>...}"
shift

# drops the first top-level block that opens with a line holding only "{"
# (caddy's global options block) and fails when there is none
strip_global() {
	awk '
		!done && !inblk && $0 == "{" { inblk = 1; next }
		inblk && $0 == "}" { inblk = 0; done = 1; next }
		inblk { next }
		{ print }
		END { if (!done) { print "assemble.sh: no global options block in " FILENAME > "/dev/stderr"; exit 1 } }
	' "$1"
}

# replaces the `tls {$<VAR>}` line of every site in a file with the node
# tls import; the file must hold exactly the expected number of them
swap_tls() {
	file="$1" var="$2" want="$3"
	n="$(grep -c "^	tls {\\\$$var}\$" "$file" || true)"
	if [ "$n" != "$want" ]; then
		echo "assemble.sh: expected $want 'tls {\$$var}' lines in $file, found $n" >&2
		exit 1
	fi
	sed "s/^	tls {\\\$$var}\$/	import sa_tls_{\$SA_TLS}/" "$file"
}

header() {
	cat <<'EOF'
# generated by deploy/caddy/assemble.sh; edit the inputs, not this file.

(sa_tls_bunny) {
	tls {
		dns bunny {env.BUNNY_API_KEY}
	}
}

(sa_tls_internal) {
	tls internal
}

EOF
}

health() {
	cat <<'EOF'

# port 80: the node's composite health for the dns monitor (assemble.sh)
http:// {
	# deploy.yml drains a node by creating /drain/draining: port 80 answers
	# 503, so the dns monitor takes the node out while https still serves
	# the clients that have not yet moved
	@draining file {
		root /drain
		try_files /draining
	}
	handle @draining {
		respond "draining" 503
	}
	handle {
		reverse_proxy {$NODE_HEALTH_UPSTREAM} {
			rewrite {$NODE_HEALTH_PATH}
			method GET
			header_up -X-Forwarded-For
			header_up -X-Real-Ip
			header_up -Forwarded
			@healthy status 200
			handle_response @healthy {
				redir https://{host}{uri} 308
			}
			handle_response {
				respond "unavailable" 503
			}
		}
	}
	handle_errors {
		respond "unavailable" 503
	}
}
EOF
}

case "$tier" in
edge)
	[ $# -eq 1 ] || { echo "usage: assemble.sh edge <edge.Caddyfile>" >&2; exit 2; }
	# edge keeps its own global block; only redirects are switched off in it
	n="$(grep -c '^{$' "$1" || true)"
	[ "$n" = 1 ] || { echo "assemble.sh: expected one global block in $1, found $n" >&2; exit 1; }
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' EXIT
	# in. and otlp. each carry one tls line
	swap_tls "$1" EDGE_TLS 2 >"$tmp"
	header
	awk '{ print } $0 == "{" && !done { print "\tauto_https disable_redirects"; done = 1 }' "$tmp"
	health
	;;
core)
	[ $# -eq 2 ] || { echo "usage: assemble.sh core <app.Caddyfile> <web.Caddyfile>" >&2; exit 2; }
	tmp="$(mktemp)" app="$(mktemp)" web="$(mktemp)"
	trap 'rm -f "$tmp" "$app" "$web"' EXIT
	strip_global "$1" >"$tmp"
	swap_tls "$tmp" APP_TLS 1 >"$app"
	strip_global "$2" >"$tmp"
	swap_tls "$tmp" WEB_TLS 1 >"$web"
	header
	cat <<'EOF'
(core_log_fields) {
	request>remote_ip delete
	request>remote_port delete
	request>client_ip delete
	request>headers delete
	request>uri regexp \?.*$ ""
	resp_headers delete
}

{
	auto_https disable_redirects
	log default {
		output stdout
		format filter {
			wrap json
			fields {
				import core_log_fields
			}
		}
	}
}

EOF
	cat "$app" "$web"
	health
	;;
*)
	echo "assemble.sh: tier must be edge or core, got $tier" >&2
	exit 2
	;;
esac
