#!/bin/sh
# assembles the caddyfile a deployed node runs (the design) from the
# per-host caddyfiles that the earlier phases test one by one:
#
#   assemble.sh edge   edge.Caddyfile                  > node.Caddyfile
#   assemble.sh core   app.Caddyfile web.Caddyfile     > node.Caddyfile
#   assemble.sh redirect redirect.Caddyfile            > node.Caddyfile
#   assemble.sh node edge.Caddyfile app.Caddyfile web.Caddyfile > node.Caddyfile
#
# node is a converged node (the three-node layout,
# docs/reference/availability.md): one caddy serves in., otlp., app. and
# web. its port 80 answers the edge health at every path except /core,
# which answers the core health, so traffic manager probes ingestion and
# dashboards separately (infra/tofu/modules/failover). it reads
# CORE_HEALTH_UPSTREAM and CORE_HEALTH_PATH beside the NODE_HEALTH_ pair.
#
# redirect is an old edge node after a handover by permanent redirect
# (infra/ansible/playbooks/cutover-redirect.yml): the same node-level parts
# as edge around redirect.Caddyfile.
#
# a core node serves app. and web. from one caddy, and caddy allows one
# global options block per config, so each input's global block is dropped
# and one node-level block replaces it. its default-logger filter deletes the
# same fields as the inputs' (app and web use identical lists; edge keeps its
# own list, which is reused unchanged).
#
# the node-level parts it adds:
#   - `tls {$EDGE_TLS}` and the like become `import sa_tls_{$SA_TLS}`, where
#     SA_TLS is "cloudflare" (acme dns-01 through caddy-dns/cloudflare,
#     reading the zone-scoped token from CLOUDFLARE_API_TOKEN at runtime),
#     "cloudflare-delegated" (the same during a handover cutover) or
#     "internal" (caddy's local ca, used by the local converge only). dns-01 is required because three edge nodes
#     serve the same names, so an http-01 or tls-alpn challenge can land on
#     another node.
#   - port 80 answers 503 while the drain flag /drain/draining exists
#     (deploy.yml mounts it), then
#   - port 80 answers for the node's composite health, whatever the host
#     header: it asks NODE_HEALTH_UPSTREAM at NODE_HEALTH_PATH, redirects to
#     https when that answers 200 and answers 503 otherwise. the traffic
#     manager monitor counts 308 as healthy (infra/tofu/modules/failover), so
#     a redirect keeps the node in dns and a 503 takes it out. automatic http->https redirects are off,
#     because they would answer 308 for in. and otlp. even on a sick node.
#   - the `metrics` global option and a plain-http listener on port 2021 that
#     serves only caddy's prometheus metrics. the compose files publish no
#     port for it: prometheus reads it through the observability relay on
#     the node's compose network. the admin api stays on loopback inside the
#     container (caddy's default), because on any other address it would
#     accept unauthenticated config changes from every host that reaches it.
#
# every replaced line must be found exactly once, so a change to an input
# that this script does not understand fails the deploy instead of shipping
# a config without dns-01 or health.
set -eu

tier="${1:?usage: assemble.sh edge|core <caddyfile>...}"
shift

# drops the first top-level block that opens with a line holding only "{"
# (caddy's global options block) and fails when there is none
strip_global() {
	awk '
		!done && !inblk && $0 == "{" { inblk = 1; next }
		inblk && $0 == "}" { inblk = 0; done = 1; next }
		inblk { next }
		{ print }
		END { if (!done) { print "assemble.sh: no global options block in " FILENAME > "/dev/stderr"; exit 1 } }
	' "$1"
}

# replaces the `tls {$<VAR>}` line of every site in a file with the node
# tls import; the file must hold exactly the expected number of them
swap_tls() {
	file="$1" var="$2" want="$3"
	n="$(grep -c "^	tls {\\\$$var}\$" "$file" || true)"
	if [ "$n" != "$want" ]; then
		echo "assemble.sh: expected $want 'tls {\$$var}' lines in $file, found $n" >&2
		exit 1
	fi
	sed "s/^	tls {\\\$$var}\$/	import sa_tls_{\$SA_TLS}/" "$file"
}

header() {
	cat <<'EOF'
# generated by deploy/caddy/assemble.sh; edit the inputs, not this file.

(sa_tls_cloudflare) {
	tls {
		dns cloudflare {env.CLOUDFLARE_API_TOKEN}
	}
}

# a handover cutover (docs/handover/plan.md section 2.3): the new nodes get
# their certificates before the domain's delegation moves to the new dns
# account. the old zone points _acme-challenge.<name> of every name at
# ACME_CHALLENGE_DOMAIN by cname, and caddy writes the dns-01 answer there,
# in a zone the new cloudflare token may edit
(sa_tls_cloudflare-delegated) {
	tls {
		dns cloudflare {env.CLOUDFLARE_API_TOKEN}
		dns_challenge_override_domain {env.ACME_CHALLENGE_DOMAIN}
	}
}

(sa_tls_internal) {
	tls internal
}

EOF
}

# one reverse_proxy that turns an upstream health answer into 308 or 503;
# $1 and $2 name the environment variables of upstream and path
health_proxy() {
	cat <<EOF
		reverse_proxy {\$$1} {
			rewrite {\$$2}
			method GET
			header_up -X-Forwarded-For
			header_up -X-Real-Ip
			header_up -Forwarded
			@healthy status 200
			handle_response @healthy {
				redir https://{host}{uri} 308
			}
			handle_response {
				respond "unavailable" 503
			}
		}
EOF
}

health() {
	cat <<'EOF'

# port 80: the node's composite health for the dns monitor (assemble.sh)
http:// {
	# deploy.yml drains a node by creating /drain/draining: port 80 answers
	# 503, so the dns monitor takes the node out while https still serves
	# the clients that have not yet moved
	@draining file {
		root /drain
		try_files /draining
	}
	handle @draining {
		respond "draining" 503
	}
EOF
	if [ "${1:-}" = node ]; then
		echo "	handle /core {"
		health_proxy CORE_HEALTH_UPSTREAM CORE_HEALTH_PATH
		echo "	}"
	fi
	echo "	handle {"
	health_proxy NODE_HEALTH_UPSTREAM NODE_HEALTH_PATH
	echo "	}"
	cat <<'EOF'
	handle_errors {
		respond "unavailable" 503
	}
}

# caddy's prometheus metrics for the observability relay (assemble.sh)
http://:2021 {
	metrics
}
EOF
}

case "$tier" in
edge | redirect)
	[ $# -eq 1 ] || { echo "usage: assemble.sh $tier <$tier.Caddyfile>" >&2; exit 2; }
	# edge keeps its own global block; only redirects are switched off in it
	n="$(grep -c '^{$' "$1" || true)"
	[ "$n" = 1 ] || { echo "assemble.sh: expected one global block in $1, found $n" >&2; exit 1; }
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' EXIT
	# in. and otlp. each carry one tls line; the redirect file adds app. and web.
	if [ "$tier" = edge ]; then want=2; else want=4; fi
	swap_tls "$1" EDGE_TLS "$want" >"$tmp"
	header
	awk '{ print } $0 == "{" && !done { print "\tauto_https disable_redirects"; print "\tmetrics"; done = 1 }' "$tmp"
	health
	;;
core | node)
	if [ "$tier" = node ]; then
		[ $# -eq 3 ] || { echo "usage: assemble.sh node <edge.Caddyfile> <app.Caddyfile> <web.Caddyfile>" >&2; exit 2; }
	else
		[ $# -eq 2 ] || { echo "usage: assemble.sh core <app.Caddyfile> <web.Caddyfile>" >&2; exit 2; }
	fi
	tmp="$(mktemp)" app="$(mktemp)" web="$(mktemp)" edge="$(mktemp)"
	trap 'rm -f "$tmp" "$app" "$web" "$edge"' EXIT
	if [ "$tier" = node ]; then
		# the edge sites keep their own log snippets; only their global
		# block goes, and the core one below replaces it (it deletes the
		# same fields and the query string as well)
		strip_global "$1" >"$tmp"
		swap_tls "$tmp" EDGE_TLS 2 >"$edge"
		shift
	fi
	strip_global "$1" >"$tmp"
	swap_tls "$tmp" APP_TLS 1 >"$app"
	strip_global "$2" >"$tmp"
	swap_tls "$tmp" WEB_TLS 1 >"$web"
	header
	cat <<'EOF'
(core_log_fields) {
	request>remote_ip delete
	request>remote_port delete
	request>client_ip delete
	request>headers delete
	request>uri regexp \?.*$ ""
	resp_headers delete
}

{
	auto_https disable_redirects
	metrics
	log default {
		output stdout
		format filter {
			wrap json
			fields {
				import core_log_fields
			}
		}
	}
}

EOF
	cat "$edge" "$app" "$web"
	health "$tier"
	;;
*)
	echo "assemble.sh: tier must be edge, core, node or redirect, got $tier" >&2
	exit 2
	;;
esac
