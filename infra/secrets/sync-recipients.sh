#!/bin/sh
# regenerates infra/secrets/.sops.yaml from infra/secrets/recipients/<env>.txt
# and re-encrypts every existing file of that environment to the new list,
# so adding or removing a person is: edit the list, run this, commit both.
#
#   infra/secrets/sync-recipients.sh
#
# a recipients file holds age public keys (age1...), one per line; lines
# starting with # name the holder. an environment without a file gets no
# rule, so nothing can be encrypted for it by accident. removing a person
# also needs rotating every secret they could read: re-encryption only stops
# them reading future versions (docs/deploy/secrets.md, "removing").
# sops matches path_regex against the path relative to .sops.yaml, so the
# rules name <env>/ only. re-encryption needs the runner's own age identity
# (SOPS_AGE_KEY_FILE), which must already be a recipient.
set -eu

dir="$(cd "$(dirname "$0")" && pwd)"
sops="${SOPS:-sops}"
out="$dir/.sops.yaml"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
	echo "# generated by infra/secrets/sync-recipients.sh from infra/secrets/recipients/<env>.txt;"
	echo "# edit those lists, not this file. docs/deploy/secrets.md has the procedure."
	echo "creation_rules:"
} >"$tmp"
rules=0
for env in staging production; do
	list="$dir/recipients/$env.txt"
	[ -f "$list" ] || continue
	keys="$(grep -v '^[[:space:]]*#' "$list" | grep -v '^[[:space:]]*$' || true)"
	if [ -z "$keys" ]; then
		echo "sync-recipients.sh: $list holds no keys" >&2
		exit 1
	fi
	for k in $keys; do
		case "$k" in
		age1*) ;;
		*) echo "sync-recipients.sh: $list: $k is not an age public key" >&2; exit 1 ;;
		esac
	done
	{
		echo "  - path_regex: (^|/)$env/[^/]+\\.enc\\.(yaml|env)\$"
		echo "    age: >-"
		for k in $keys; do echo "      $k,"; done | sed '$ s/,$//'
	} >>"$tmp"
	rules=$((rules + 1))
done
[ "$rules" -gt 0 ] || echo "  []" >>"$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out with $rules rule(s)"

# re-encrypt existing files so the data key is shared with the new list
for f in "$dir"/staging/*.enc.* "$dir"/production/*.enc.*; do
	[ -f "$f" ] || continue
	(cd "$dir/../.." && "$sops" --config "$out" updatekeys --yes "$f")
done
